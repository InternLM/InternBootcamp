class FinanceInstructionGenerator(BaseInstructionGenerator):
    def __init__(self, 
                 scale_range=[100, 800], 
                 # 基础盈利能力参数
                 base_gross_margin_range=[0.20, 0.45],
                 opex_ratio_range=[0.08, 0.15],
                 tax_rate=0.25,
                 
                 # 营运效率参数 (天数)
                 inventory_days_range=[45, 90],
                 receivable_days_range=[30, 60],
                 payable_days_range=[40, 80],
                 
                 # 资产结构参数
                 fixed_asset_ratio_range=[0.25, 0.50], # 重资产程度
                 
                 # 财务杠杆与融资行为
                 initial_leverage_range=[1.5, 2.5], # 初始 资产/权益
                 dividend_payout_ratio=0.3,
                 
                 # 波动性与情境概率
                 volatility_revenue=0.10, # 营收正常波动率
                 prob_cost_shock=0.3,     # 发生“增收不增利”或“成本暴涨”的概率
                 prob_seo_event=0.2       # 发生重大增发/注资的概率
                 ):
        super().__init__()
        self.scale_range = scale_range
        self.base_gross_margin_range = base_gross_margin_range
        self.opex_ratio_range = opex_ratio_range
        self.tax_rate = tax_rate
        self.inventory_days_range = inventory_days_range
        self.receivable_days_range = receivable_days_range
        self.payable_days_range = payable_days_range
        self.fixed_asset_ratio_range = fixed_asset_ratio_range
        self.initial_leverage_range = initial_leverage_range
        self.dividend_payout_ratio = dividend_payout_ratio
