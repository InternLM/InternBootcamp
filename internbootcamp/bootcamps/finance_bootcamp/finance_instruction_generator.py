    def _get_random_value(self, range_tuple):
        return np.random.uniform(range_tuple[0], range_tuple[1])

    def _simulate_volatile_company(self, base_start_revenue):
        years = ["2021", "2022", "2023"]
        data = {}

        # --- 1. 初始化 (T-1期状态) ---
        # 设定一个“锚定”的毛利率和费用率，但每年会偏离它
        anchor_gross_margin = self._get_random_value(self.base_gross_margin_range)
        anchor_opex_ratio = self._get_random_value(self.opex_ratio_range)
        
        # 初始化 T-1 期数据 (用于计算 T0 的现金流变动)
        last_revenue = base_start_revenue
        last_cost = last_revenue * (1 - anchor_gross_margin)
        
        # 初始资产负债表推导
        last_inv_days = self._get_random_value(self.inventory_days_range)
        last_rec_days = self._get_random_value(self.receivable_days_range)
        last_pay_days = self._get_random_value(self.payable_days_range)
        
        last_inventory = last_cost / 365 * last_inv_days
        last_receivables = last_revenue / 365 * last_rec_days
        last_payables = last_cost / 365 * last_pay_days
        
        # 初始权益
        initial_leverage = self._get_random_value(self.initial_leverage_range)
        initial_total_assets = (last_inventory + last_receivables) * 2.5 # 粗略估计
        last_equity = initial_total_assets / initial_leverage
        
        # 初始债务 (粗略)
        last_total_debt = max(0, initial_total_assets - last_equity - last_payables)
        
        # 状态机变量
        current_equity = last_equity
        current_debt_stock = last_total_debt # 存量有息负债
        
        # 债务结构偏好 (长短期比例)
        lt_debt_ratio = np.random.uniform(0.3, 0.7)

        for year in years:
            # ==========================================
            # 步骤 1: 利润表 (Income Statement)
            # ==========================================
            
            # 1.1 营收生成 (带趋势的随机游走)
            rev_growth = np.random.normal(0.05, self.volatility_revenue) # 平均5%增长
            revenue = last_revenue * (1 + rev_growth)
            
            # 1.2 成本生成 (模拟真实案例中的“剪刀差”)
            # 正常情况下成本随营收走，但有概率发生“成本冲击”(Cost Shock)
            is_cost_shock = np.random.random() < self.prob_cost_shock
            
            if is_cost_shock:
                # 场景：营收可能持平或微跌，但原材料暴涨 -> 毛利被大幅压缩
                # 强制让毛利率下降 5% - 15%
                current_gross_margin = anchor_gross_margin - np.random.uniform(0.05, 0.15)
                # 保护机制
                current_gross_margin = max(0.05, current_gross_margin)
            else:
                # 正常波动
                current_gross_margin = anchor_gross_margin + np.random.normal(0, 0.02)
            
            cost = revenue * (1 - current_gross_margin)
            
            # 1.3 费用与利润
            opex = revenue * anchor_opex_ratio * np.random.uniform(0.95, 1.05)
            # 模拟研发或管理费用的刚性（营收跌时费用不一定跌）
            if rev_growth < 0:
                opex = max(opex, last_revenue * anchor_opex_ratio * 0.95)

            op_profit = revenue - cost - opex
            
            # 利息支出估算 (基于上一期债务)
            interest_expense = current_debt_stock * 0.05 
            total_profit = op_profit - interest_expense
            
            # 净利润
            net_profit = total_profit * (1 - self.tax_rate)
            
            # ==========================================
            # 步骤 2: 资产负债表驱动 (BS Drivers)
            # ==========================================
            
            # 2.1 权益变动 (Equity Waterfall)
            # 基础变动：+净利 -分红
            div_payout = max(0, net_profit * self.dividend_payout_ratio) if net_profit > 0 else 0
            organic_equity_change = net_profit - div_payout
            
            # 特殊事件：SEO (增发) 或 注资
            # 真实数据特征：某一年权益突然暴涨，通常伴随着债务下降
            seo_amount = 0
            if np.random.random() < self.prob_seo_event:
                seo_amount = revenue * np.random.uniform(0.2, 0.5) # 融资额约为营收的20%-50%
            
            end_equity = current_equity + organic_equity_change + seo_amount
            
            # 2.2 营运资本 (Working Capital)
            inv_days = self._get_random_value(self.inventory_days_range)
            rec_days = self._get_random_value(self.receivable_days_range)
            pay_days = self._get_random_value(self.payable_days_range)
            
            # 模拟存货积压 (如果营收下降，周转天数通常变长)
            if rev_growth < 0:
                inv_days *= 1.2
            
            inventory = cost / 365 * inv_days
            receivables = revenue / 365 * rec_days
            payables = cost / 365 * pay_days
            
            # 2.3 长期资产 (PPE)
            # 固定资产具有刚性，每年 = 上年 + Capex - 折旧
            # 简化模型：锚定营收的一定比例，但平滑处理
            target_ppe = revenue * self._get_random_value(self.fixed_asset_ratio_range)
            # 折旧
            depreciation = target_ppe * 0.08 # 假设平均折旧率
            amortization = revenue * 0.01
            
            non_current_assets = target_ppe
            
            # ==========================================
            # 步骤 3: 债务与现金的动态配平 (The Plug)
            # ==========================================
            
            # 逻辑：
            # 资金占用 (Uses) = 非现金流动资产 + 长期资产
            # 资金来源 (Sources) = 权益 + 经营性负债(应付) + 有息债务
            # 缺口 = 现金
            
            operating_assets = inventory + receivables + non_current_assets
            stable_funding = end_equity + payables
            
            # 计算资金缺口 (Funding Gap)
            # 我们希望保持一定的现金水位 (Min Cash)
            min_cash = revenue * 0.10
            target_capital_employed = operating_assets + min_cash
            
            required_debt = target_capital_employed - stable_funding
            
            # 如果刚刚融了资 (SEO)，required_debt 可能会变成负数（钱太多了）
            # 这种情况下，我们假设公司会还债，剩下的变成现金
            
            if required_debt < 0:
                # 钱够多了，有息负债降为0 (或保留极少量)，剩下全是现金
                financial_debt = revenue * 0.02 # 保留一点点维持银行关系
                final_cash = stable_funding + financial_debt - operating_assets
            else:
                # 需要借钱
                financial_debt = required_debt
                final_cash = min_cash
            
            # 确保资产=负债+权益
            total_assets = final_cash + operating_assets
            total_liabilities = payables + financial_debt
            
            # 再次校验配平 (浮点数误差处理)
            balance_check = total_assets - (total_liabilities + end_equity)
            if abs(balance_check) > 0.01:
                final_cash -= balance_check # 强行配平到现金
                total_assets -= balance_check

            # ==========================================
            # 步骤 4: 细项拆分与现金流计算
            # ==========================================
            
            # 4.1 债务结构拆解
            # 真实数据特征：如果发生SEO，通常先还短期借款
            if seo_amount > 0:
                # 融资年，大幅降低短债比例
                st_debt_ratio = 0.2
            else:
                # 正常年份，短债比例较高
                st_debt_ratio = np.random.uniform(0.5, 0.8)
                
            st_financial_debt = financial_debt * st_debt_ratio
            lt_financial_debt = financial_debt * (1 - st_debt_ratio)
            
            # 细分科目
            st_borrowing = st_financial_debt * 0.8
            non_current_1y = st_financial_debt * 0.15
            st_fin_pay = st_financial_debt * 0.05
            
            lt_borrowing = lt_financial_debt * 0.6
            bonds = lt_financial_debt * 0.3
            lease_liab = lt_financial_debt * 0.1
            
            # 4.2 现金流 (CFO)
            # 直接法/间接法逻辑
            delta_inv = inventory - last_inventory
            delta_rec = receivables - last_receivables
            delta_pay = payables - last_payables # 注意：这里用的是payables(经营性)
            
            cfo = net_profit + depreciation + amortization - delta_inv - delta_rec + delta_pay
            
            # 修正：真实数据中，如果利润暴跌但CFO还行，通常是因为存货减少或应付增加
            # 这里代码逻辑已经包含了delta，无需硬编码，自然生成即可
            
            # Capex
            capex = depreciation * np.random.uniform(1.2, 1.8) # 维持增长需要Capex > Depr

            # 4.3 汇总数据
            current_assets = final_cash + inventory + receivables
            current_liabilities = payables + st_financial_debt
            
            data_map = {
                "营业收入": revenue,
                "营业利润": op_profit,
                "净利润": net_profit,
                "固定资产折旧、油气资产折耗、生产性生物资产折旧": depreciation,
                "无形资产摊销": amortization,
                "营业成本": cost,
                "经营活动现金净流量": cfo,
                "资本支出": capex,
                "短期借款": st_borrowing,
                "长期借款": lt_borrowing,
                "应付债券": bonds,
                "租赁负债": lease_liab,
                "一年内到期的非流动负债": non_current_1y,
                "应付短期融资款": st_fin_pay,
                "总资产": total_assets,
                "所有者权益": end_equity,
                "负债与所有者权益合计": total_assets,
                "流动资产合计": current_assets,
                "流动负债合计": current_liabilities,
                "存货净额": inventory,
                "货币资金": final_cash
            }
            
            data[year] = {k: round(v, 4) for k, v in data_map.items()}

            # 更新状态
            last_revenue = revenue
            current_equity = end_equity
            current_debt_stock = financial_debt
            last_inventory = inventory
            last_receivables = receivables
            last_payables = payables
            
        return data

    def case_generator(self) -> Dict[str, Any]:
        shuffled_titles = self.titles.copy()
        random.shuffle(shuffled_titles)
        base_scale = self._get_random_value(self.scale_range)
        data_years = self._simulate_volatile_company(base_scale)
        formatted_data = {}
        for year, values in data_years.items():
            formatted_data[year] = [values.get(t, 0.0) for t in shuffled_titles]
        return {
            "data": formatted_data,
            "titles": shuffled_titles
        }

    def numpy_to_markdown(self, array, headers):
        n_rows, _ = array.shape
        lines = []
        header_line = "| " + " | ".join(headers) + " |"
        lines.append(header_line)
        separator = "|" + "|".join(["---"] * len(headers)) + "|"
        lines.append(separator)
        for i in range(n_rows):
            row_data = []
            for j in range(len(headers)):
                row_data.append(str(array[i, j]))
            row_line = "| " + " | ".join(row_data) + " |"
            lines.append(row_line)
        return "\n".join(lines)

